import fs from 'node:fs/promises';
import path from 'node:path';
import type { CaseFileEntry, CaseMode, CaseSource } from '../protocol/types.js';
import { shortSha } from '../util/ids.js';

export interface ContextInput {
  mode: CaseMode;
  source: CaseSource;
  repoRoot: string;
  base: string;
  head: string;
  fixCommit: string | null;
  subject: string;
  body: string;
  files: CaseFileEntry[];
  diffPath: string;
  contextPath: string;
  rulesFiles: string[];
}

export async function detectRulesFiles(repoRoot: string): Promise<string[]> {
  const candidates = ['AGENTS.md', 'CLAUDE.md', 'CONTRIBUTING.md', 'README.md'];
  const found: string[] = [];
  for (const candidate of candidates) {
    try {
      await fs.access(path.join(repoRoot, candidate));
      found.push(candidate);
    } catch {
      continue;
    }
  }
  return found;
}

export function generateContextMd(input: ContextInput): string {
  const additions = input.files.reduce((total, file) => total + file.additions, 0);
  const deletions = input.files.reduce((total, file) => total + file.deletions, 0);
  const fileLines = input.files.length === 0
    ? '- (empty diff)'
    : input.files
        .map((file) => `- \`${file.path}\` (${file.status}, +${file.additions}/-${file.deletions})`)
        .join('\n');
  const rules = input.rulesFiles.length === 0
    ? '- none detected at the repository root'
    : input.rulesFiles.map((file) => `- \`${file}\` (read it from the snapshot)`).join('\n');
  return `# Review Context (generated by llm-review-bench)

This file is immutable for this run. Every reviewer receives the same case facts and no
access to gold labels, other reviewer output, or adjudication records.

## 1. Objective

${input.subject}

${input.body.length > 0 ? input.body : '(no commit body)'}

## 2. Review range

- Mode: ${input.mode}
- Source: ${input.source}
- Repository: \`${input.repoRoot}\`
- Review range: \`${shortSha(input.base)}..${shortSha(input.head)}\`
- Base: \`${input.base}\`
- Head: \`${input.head}\`
- Fix commit: ${input.fixCommit === null ? '(live case, no fix commit)' : '(withheld from reviewers)'}
- Review worktree: current working directory (checked out at the head commit)
- Unified diff: \`${input.diffPath}\`

### Change statistics

- Files: ${input.files.length}
- Additions: ${additions}
- Deletions: ${deletions}

### Files

${fileLines}

## 3. Applicable repository rules

${rules}

## 4. Review focus

- Correctness of the changed behavior, including error, cancellation, timeout, and
  partial-failure paths.
- Concurrency, ordering, visibility, and lifecycle invariants when the diff touches them.
- API and documented-contract drift caused by the change.
- Missing tests only when the missing test protects a concrete failure mode introduced
  or revealed by the diff.

Do not report style-only nits, pre-existing defects outside the diff, or speculative
concerns without a concrete trigger and observable consequence.

## 5. Scope and independence

- Review only the change in the range above. The parent state is the base commit.
- The current working directory is a read-only checkout at the head commit. Do not modify it.
- Gold labels and other reviewers' findings are intentionally unavailable.
- Return one JSON object as specified by the run prompt; an empty findings array is a
  valid review.
`;
}

export function renderPrompt(input: {
  context: string;
  contextPath: string;
  diffPath: string;
  base: string;
  head: string;
  budget: number;
}): string {
  return `You are one independent reviewer in the llm-review-bench benchmark.

Review the change from ${input.base} to ${input.head}. The current working directory is a
read-only git worktree snapshot at the head commit. The unified diff is at ${input.diffPath};
the shared context is at ${input.contextPath}. Do not modify the snapshot. Do not read
benchmark gold labels, adjudication records, or other reviewers' output.

Return exactly one JSON object and nothing else (no Markdown fences, no prose):

{
  "summary": "one short paragraph describing the review",
  "findings": [
    {
      "file": "repository-relative/path.ext",
      "lineStart": 123,
      "lineEnd": 130,
      "title": "short defect title",
      "trigger": "concrete input, interleaving, or condition that reaches the defect",
      "consequence": "observable failure or contract violation",
      "evidence": "code path with file:line references",
      "severity": "P0|P1|P2|P3",
      "confidence": 0.0,
      "suggestedFix": "actionable fix"
    }
  ]
}

Rules:
- Report only defects introduced or materially exposed by this change.
- Every finding must have a concrete trigger and a user-observable consequence.
- Cite repository-relative files and the line range in the head snapshot.
- confidence is a number from 0 to 1.
- At most ${input.budget} findings. Return {"summary":"...","findings":[]} when you find
  nothing; do not return an empty response or prose.
- Do not include shell commands, patches, or hidden reasoning outside the JSON object.

## Shared context (verbatim, immutable)

${input.context}`;
}
